import {defineType, defineField} from 'sanity'

export const galleryEvent = defineType({
  name: 'galleryEvent',
  title: 'Gallery Event',
  type: 'document',
  fields: [
    defineField({
      name: 'title',
      title: 'Title',
      type: 'string',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'image',
      title: 'Image',
      type: 'image',
      options: {hotspot: true},
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'description',
      title: 'Description',
      type: 'text',
      rows: 3,
    }),
  ],
  preview: {
    select: {title: 'title', media: 'image', subtitle: 'description'},
  },
})